import { createRequire } from "node:module";
import { describe, expect, it } from "vitest";

const require = createRequire(import.meta.url);
const { createTsProject, loadSourceFile } = require("../../entities/ast");
const css = require("../../css");
const { classifyValue } = require("../../css/values");
const { classFacts } = require("../../css/tailwind");

// CSS is a FACT source, not a rule. These tests pin what is READ — declarations,
// the TYPE of each written value, the calls by their own names, the read of a
// variable — never a vocabulary this repo maintains: no test here asserts "16px is
// a length" because the reader calls it a `dimension`, and nothing asserts a list
// of colour functions, because there is no list.
//
// The fixtures are real code: a styled-components block with theme reads and a
// nested state selector, an SCSS partial with variables, interpolation, mixins and
// `math.div`, and a Tailwind class list whose CSS is generated by Tailwind itself.

const STYLED = `
export const StyledButton = styled.button<{ $size: "small" }>\`
  display: flex;
  height: \${({ theme }) => theme.elements.form.height};
  padding: 16px;
  color: \${({ theme }) => theme.colors.highlighted};
  border: 1px solid #fff;
  background: var(--section-bg);
  width: calc(100% - 2px);
  opacity: 0.5;

  &:disabled {
    opacity: 0.4;
  }
\`;
`;

const templateOf = (code) => {
	const sf = loadSourceFile(createTsProject(), "a/button.tsx", code);
	const nodes = sf.getDescendantsOfKind(require("ts-morph").SyntaxKind.TaggedTemplateExpression);

	return nodes.map((node) => css.templateFacts(node));
};

describe("css — a styled-components block", () => {
	const [facts] = templateOf(STYLED);

	it("reads every declaration in document order, nested rules included", () => {
		expect(facts.tag).toBe("styled.button");
		expect(facts.declarations.map((decl) => decl.prop)).toEqual(["display", "height", "padding", "color", "border", "background", "width", "opacity", "opacity"]);
	});

	it("a typed value is reported by its parser type, not by a word of ours", () => {
		expect(facts.declarations.find((decl) => decl.prop === "padding").literals).toEqual([{ kind: "dimension", text: "16px", unit: "px", line: 4 }]);
		// `border: 1px solid #fff` — a dimension AND a hash, both read from the grammar
		expect(facts.declarations.find((decl) => decl.prop === "border").literals.map((literal) => [literal.kind, literal.text])).toEqual([
			["dimension", "1px"],
			["hash", "#fff"],
		]);
	});

	it("a value that comes from the theme has NO literals, and its call is named", () => {
		const height = facts.declarations.find((decl) => decl.prop === "height");
		expect(height.literals).toEqual([]);
		// the `${…}` was substituted, and the link back to the expression is kept
		expect(facts.exprs.map((expr) => expr.index)).toEqual([0, 1]);
		expect(facts.exprs[0].text).toContain("theme.elements.form.height");
		// What a value QUOTES is a fact of the declaration, not a word of the reader's.
		expect(facts.declarations.filter((decl) => (decl.reads ?? []).length).length).toBe(2);
	});

	it("a declaration reads the expression IN ITS OWN VALUE, by position", () => {
		const height = facts.declarations.find((decl) => decl.prop === "height");
		const color = facts.declarations.find((decl) => decl.prop === "color");

		expect(height.reads.map((read) => read.text)).toEqual(["({ theme }) => theme.elements.form.height"]);
		expect(color.reads.map((read) => read.text)).toEqual(["({ theme }) => theme.colors.highlighted"]);
		// …and a declaration that quotes nothing is not handed a neighbour's value.
		expect(facts.declarations.find((decl) => decl.prop === "padding").reads).toEqual([]);
	});

	it("`var(--x)` is a read; `calc(…)` is a call with its arguments read too", () => {
		expect(facts.declarations.find((decl) => decl.prop === "background").vars).toEqual(["--section-bg"]);

		const width = facts.declarations.find((decl) => decl.prop === "width");
		expect(width.functions.map((fn) => fn.name)).toEqual(["calc"]);
		// both arguments are values like any other: a percentage and a dimension
		expect(width.literals.map((literal) => [literal.kind, literal.text])).toEqual([
			["percentage", "100%"],
			["dimension", "2px"],
		]);
	});

	it("a colour function is reported by name, with its arguments", () => {
		const mixed = classifyValue("color-mix(in srgb, var(--a) 40%, #fff)", 1);
		expect(mixed.parsed).toBe(true);
		expect(mixed.functions.map((fn) => fn.name)).toEqual(["color-mix"]);
		expect(mixed.vars).toEqual(["--a"]);
		expect(mixed.literals.map((literal) => literal.kind)).toEqual(["percentage", "hash"]);
	});
});

describe("css — a template is CSS by its CONTENT, not by its tag's name", () => {
	// Any tagged template whose substituted text reads as CSS becomes facts —
	// `createGlobalStyle`, `keyframes`, a tag nobody has heard of. A template
	// whose text is another language (SQL, GraphQL, JSON, prose) does not,
	// whatever it is called. No list of tag names, no consumer option.
	const CODE = `
export const Global = createGlobalStyle\`
  html { color: #000; }
\`;
export const Motion = keyframes\`
  from { opacity: 0; }
  to { opacity: 1; }
\`;
export const Query = sql\`
  SELECT * FROM users WHERE id = 1
\`;
export const Data = json\`
  {"a": 1, "b": [2]}
\`;
export const Words = prose\`
  hello world, this is just text
\`;
`;

	const candidatesOf = () => {
		const rel = "a/global.tsx";
		const sf = loadSourceFile(createTsProject(), rel, CODE);
		const candidates = [
			{ name: "Global", lines: [2, 4] },
			{ name: "Motion", lines: [5, 8] },
			{ name: "Query", lines: [9, 11] },
			{ name: "Data", lines: [12, 14] },
			{ name: "Words", lines: [15, 17] },
		];
		css.attachToCandidates(candidates, { sf });

		return candidates;
	};

	it("a CSS template is read whatever its tag is called", () => {
		const [global, motion] = candidatesOf();
		expect(global.css.templates).toHaveLength(1);
		expect(global.css.templates[0].tag).toBe("createGlobalStyle");
		expect(global.css.templates[0].declarations.map((decl) => decl.prop)).toEqual(["color"]);
		expect(motion.css.templates).toHaveLength(1);
		expect(motion.css.templates[0].tag).toBe("keyframes");
		expect(motion.css.templates[0].declarations.map((decl) => decl.prop)).toEqual(["opacity", "opacity"]);
	});

	it("a template in another language is not CSS, whatever its tag is called", () => {
		const [, , query, data, words] = candidatesOf();
		expect(query.css).toBeUndefined();
		expect(data.css).toBeUndefined();
		expect(words.css).toBeUndefined();
	});
});

describe("css — SCSS is read, not skipped", () => {
	// The exact shapes that make SCSS not CSS. Every one of them used to produce
	// "no facts", which reads as "nothing hardcoded" — the opposite of the truth.
	const cases = [
		["$gap", "a variable reference"],
		["calc(100% - #{$gap})", "interpolation inside a call"],
		["math.div($a, 2)", "a module function"],
		["map-get($map, spacing)", "a helper call"],
		["1px solid $border-color", "a shorthand with a variable"],
	];

	it("a value the CSS grammar rejects is recorded as TOKENS, and says so", () => {
		for (const [value] of cases) {
			const facts = classifyValue(value, 1);
			expect(facts.parsed, value).toBe(false);
		}
	});

	it("the tokens are the parts that matter: variables, interpolations, calls, numbers", () => {
		expect(classifyValue("$gap", 1).vars).toEqual(["$gap"]);
		expect(classifyValue("1px solid $border-color", 1).vars).toEqual(["$border-color"]);
		expect(classifyValue("1px solid $border-color", 1).literals.map((literal) => literal.text)).toEqual(["1px"]);

		const interpolated = classifyValue("calc(100% - #{$gap})", 1);
		expect(interpolated.interpolations.map((entry) => entry.text)).toEqual(["#{$gap}"]);
		expect(interpolated.functions.map((fn) => fn.name)).toEqual(["calc"]);

		const div = classifyValue("math.div($a, 2)", 1);
		expect(div.functions.map((fn) => fn.name)).toEqual(["math.div"]);
		expect(div.vars).toEqual(["$a"]);
	});
});

describe("css — a real stylesheet", () => {
	const sheet = `.card {
  display: grid;
  gap: var(--gap, 8px);
  padding: 16px 24px;
  color: #123456;
}

.card__title {
  font-size: clamp(1rem, 2vw, 1.5rem);
  color: oklch(70% 0.4 20);
}
`;

	it("reads rules, declarations and their order", () => {
		const facts = css.stylesheetFacts("a/card.css", sheet);
		expect(facts.rules.map((rule) => rule.selector)).toEqual([".card", ".card__title"]);
		expect(facts.declarations.slice(0, 4).map((decl) => [decl.index, decl.prop, decl.prev, decl.next])).toEqual([
			[0, "display", null, "gap"],
			[1, "gap", "display", "padding"],
			[2, "padding", "gap", "color"],
			[3, "color", "padding", "font-size"],
		]);
	});

	it("a shorthand with two dimensions yields two values, not one string", () => {
		const facts = css.stylesheetFacts("a/card.css", sheet);
		expect(facts.declarations[2].literals.map((literal) => literal.text)).toEqual(["16px", "24px"]);
	});

	it("clamp() is a call whose three arguments are values of their own", () => {
		const facts = css.stylesheetFacts("a/card.css", sheet);
		const size = facts.declarations.find((decl) => decl.prop === "font-size");
		expect(size.functions.map((fn) => fn.name)).toEqual(["clamp"]);
		expect(size.literals.map((literal) => literal.text)).toEqual(["1rem", "2vw", "1.5rem"]);
	});

	it("a syntax nobody registered produces nothing instead of being read as CSS", () => {
		expect(css.stylesheetFacts("a/card.less", ".a { color: red; }")).toBeNull();
	});
});

describe("css — the same value written for Tailwind", () => {
	// A class list is a declaration list in a string. What each class SETS comes from
	// Tailwind's own generator, so this asserts Tailwind's answer, not our table.
	const CLASSES = "grid grid-cols-3 gap-x-4 gap-y-2 place-content-between truncate aspect-video inset-x-0 ring-2 ring-offset-2 backdrop-blur-sm space-y-4 text-ellipsis";

	it("every class is resolved by Tailwind, and the properties are Tailwind's", () => {
		const facts = classFacts(CLASSES);
		expect(facts).toHaveLength(13);
		expect(facts.every((entry) => entry.known)).toBe(true);

		const properties = new Set(facts.flatMap((entry) => entry.properties));
		// Tailwind's own answers: `inset-x-0` is `left` + `right`, `space-y-4` is
		// margins plus its reverse variable, `ring-2` is a box-shadow pair.
		for (const property of ["display", "grid-template-columns", "column-gap", "row-gap", "place-content", "text-overflow", "overflow", "aspect-ratio", "left", "right", "box-shadow", "backdrop-filter", "margin-top", "margin-bottom", "--tw-space-y-reverse"]) {
			expect(properties.has(property), property).toBe(true);
		}
	});

	it("the same utility under a variant is the same property set", () => {
		expect(classFacts("md:hover:grid-cols-3")[0].properties).toEqual(classFacts("grid-cols-3")[0].properties);
	});

	it("a class Tailwind does not generate is not silently a class", () => {
		expect(classFacts("grid-cols-13").some((entry) => entry.known === false)).toBe(true);
	});
});
